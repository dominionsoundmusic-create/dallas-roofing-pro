#!/usr/bin/env python3
"""Write SERVICES.md (every page, URL, type, target keyword with volume and SEO difficulty) from
docs/keyword-plan.md and docs/towns.json. Run after scripts/keyword_plan.py."""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
plan = (ROOT / "docs" / "keyword-plan.md").read_text()
towns = json.loads((ROOT / "docs" / "towns.json").read_text())
targets = {}
for m in re.finditer(r"^### (\S+)[^\n]*\n\n- Target: \*\*(.+?)\*\*(?: \((\d+)/mo, SD (\d+), (\w+)\))?", plan, re.M):
    targets[m.group(1)] = (m.group(2), m.group(3) or "", m.group(4) or "")

CORE = [("Home", "/"), ("Services overview", "/services/"), ("Service areas overview", "/service-areas/"),
        ("How it works", "/how-it-works/"), ("About", "/about/"), ("FAQ", "/faq/"), ("Contact", "/contact/"),
        ("Contact thanks", "/contact/thanks/"), ("Hail claim checklist", "/hail-claim-checklist/"),
        ("Checklist thanks", "/hail-claim-checklist/thanks/"), ("Privacy policy", "/privacy-policy.html"),
        ("Terms", "/terms.html"), ("404", "/404.html")]
SERVICES = [("Roof repair", "/roof-repair/"), ("Roof replacement", "/roof-replacement/"),
            ("Roof leak repair", "/roof-leak-repair/"), ("Storm damage roof repair", "/storm-damage-roof-repair/"),
            ("Hail damage roof repair", "/hail-damage-roof-repair/"), ("Wind damage roof repair", "/wind-damage-roof-repair/"),
            ("Roof inspection", "/roof-inspection/"), ("Emergency roof repair and tarping", "/emergency-roof-repair/"),
            ("Commercial roofing", "/commercial-roofing/"), ("Flat roof repair", "/flat-roof-repair/"),
            ("Metal roofing", "/metal-roofing/"), ("Roof flashing repair", "/roof-flashing-repair/")]
GUIDES = [("Roof replacement cost in Dallas-Fort Worth", "/roof-replacement-cost-dallas/"),
          ("Roof insurance claims in Texas", "/roof-insurance-claim-texas/"),
          ("How to check a roofer before hiring (Texas license question)", "/do-roofers-need-a-license-in-texas/"),
          ("How long a roof lasts in North Texas", "/how-long-does-a-roof-last-in-texas/"),
          ("What to do after storm damage to a roof", "/what-to-do-after-storm-damage-to-roof/")]


def row(name, url):
    t = targets.get(url, ("none (support page)", "", ""))
    return f"| {name} | {url} | {t[0]} | {t[1] or '-'} | {t[2] or '-'} |"


q = {k: v for k, v in towns.items() if v["qualifies"]}
out = ["# SERVICES.md: DFW Expert Roofers page plan (Playbook 2.0, Oct 13 2026)", "",
       "Written before any page (CLAUDE.md). Generated by `python3 scripts/services_md.py` from",
       "docs/keyword-plan.md and docs/towns.json (Ubersuggest, United States, Oct 13 2026). Volume = monthly",
       "searches, SD = Ubersuggest SEO difficulty. Every keyword with 10+ searches is assigned or listed as unused",
       "in docs/keyword-plan.md.", "",
       f"Pages: {len(CORE)} core, {len(SERVICES)} service, {len(GUIDES)} guide, {len(q)} town = "
       f"{len(CORE) + len(SERVICES) + len(GUIDES) + len(q)} in total.", "",
       "## Core pages", "", "| Page | URL | Target keyword | Volume | SD |", "|---|---|---|---:|---:|"]
out += [row(n, u) for n, u in CORE]
out += ["", "## Service pages", "", "| Service | URL | Target keyword | Volume | SD |", "|---|---|---|---:|---:|"]
out += [row(n, u) for n, u in SERVICES]
out += ["", "## Guide pages", "", "| Guide | URL | Target keyword | Volume | SD |", "|---|---|---|---:|---:|"]
out += [row(n, u) for n, u in GUIDES]
out += ["", f"## Town pages ({len(q)})", "",
        "Maurice's rule: a DFW town with 10+ monthly searches on a Texas, roofing, non-company keyword gets a page.",
        "The 15 towns with live pages keep their URLs; new towns use /roofing-<town>-tx/.", "",
        "| Town | URL | Target keyword | Volume | SD | Qualifying rows (10+) |", "|---|---|---|---:|---:|---|"]
for k, v in sorted(q.items(), key=lambda kv: kv[1]["name"]):
    out.append(f"| {v['name']}{' (existing URL)' if v['existing'] else ''} | {v['url']} | {v['target']} | {v['volume']} | {v['sd']} | "
               f"{'; '.join(v['qualifying_rows'])} |")
out += ["", "## Towns checked that get no page", ""]
for k, v in sorted(towns.items()):
    if not v["qualifies"]:
        out.append(f"- {v['name']}: no Texas roofing row with 10+ searches that is not a company name (details in docs/keyword-plan.md).")
(ROOT / "SERVICES.md").write_text("\n".join(out) + "\n")
print(f"SERVICES.md written: {len(CORE) + len(SERVICES) + len(GUIDES) + len(q)} pages")
